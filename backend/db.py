import os
import json
import sqlite3
import psycopg
from psycopg.rows import dict_row
from contextlib import closing
from pathlib import Path
from dotenv import load_dotenv

# Ensure env vars are loaded
load_dotenv()

def is_postgres():
    return bool(os.environ.get("DATABASE_URL"))

def _connect(db_path):
    if is_postgres():
        return closing(psycopg.connect(os.environ.get("DATABASE_URL"), row_factory=dict_row))
    else:
        conn = sqlite3.connect(str(db_path))
        conn.row_factory = sqlite3.Row
        return closing(conn)

def _q(query):
    if is_postgres():
        return query.replace("?", "%s")
    return query

def init_db(db_path: str | Path) -> None:
    if is_postgres():
        schema = """
        CREATE TABLE IF NOT EXISTS meetings (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            date TEXT,
            attendees TEXT NOT NULL DEFAULT '[]',
            transcript TEXT NOT NULL,
            notes TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT (now()::text)
        );
        """
        with _connect(None) as conn:
            with conn:
                conn.execute(schema)
    else:
        Path(db_path).parent.mkdir(parents=True, exist_ok=True)
        schema = """
        CREATE TABLE IF NOT EXISTS meetings (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            date TEXT,
            attendees TEXT NOT NULL DEFAULT '[]',
            transcript TEXT NOT NULL,
            notes TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT (datetime('now'))
        );
        """
        with _connect(db_path) as conn:
            with conn:
                conn.executescript(schema)

def _row_to_meeting(row) -> dict:
    # row behaves as a dict for both sqlite3.Row and dict_row
    return {
        "id": row["id"],
        "title": row["title"],
        "date": row["date"],
        "attendees": json.loads(row["attendees"]),
        "transcript": row["transcript"],
        "notes": json.loads(row["notes"]),
        "created_at": row["created_at"],
    }

def create_meeting(db_path, title, date, attendees, transcript, notes) -> dict:
    query = _q("INSERT INTO meetings (title, date, attendees, transcript, notes) VALUES (?, ?, ?, ?, ?)")
    if is_postgres():
        query += " RETURNING id"
    
    with _connect(db_path) as conn:
        with conn:
            cursor = conn.execute(
                query,
                (
                    title,
                    date,
                    json.dumps(attendees, ensure_ascii=False),
                    transcript,
                    json.dumps(notes, ensure_ascii=False),
                ),
            )
            if is_postgres():
                meeting_id = cursor.fetchone()["id"]
            else:
                meeting_id = cursor.lastrowid
    return get_meeting(db_path, meeting_id)

def list_meetings(db_path) -> list[dict]:
    query = "SELECT id, title, date, attendees, created_at FROM meetings ORDER BY created_at DESC, id DESC"
    with _connect(db_path) as conn:
        rows = conn.execute(query).fetchall()
    return [
        {
            "id": row["id"],
            "title": row["title"],
            "date": row["date"],
            "attendees": json.loads(row["attendees"]),
            "created_at": row["created_at"],
        }
        for row in rows
    ]

def get_meeting(db_path, meeting_id: int) -> dict | None:
    query = _q("SELECT * FROM meetings WHERE id = ?")
    with _connect(db_path) as conn:
        row = conn.execute(query, (meeting_id,)).fetchone()
    return _row_to_meeting(row) if row else None

def update_meeting(db_path, meeting_id: int, **fields) -> dict | None:
    allowed = {"title", "date", "attendees", "transcript", "notes"}
    updates = {k: v for k, v in fields.items() if k in allowed and v is not None}
    if not updates:
        return get_meeting(db_path, meeting_id)
    if "attendees" in updates:
        updates["attendees"] = json.dumps(updates["attendees"], ensure_ascii=False)
    if "notes" in updates:
        updates["notes"] = json.dumps(updates["notes"], ensure_ascii=False)
    assignments = ", ".join(f"{key} = ?" for key in updates)
    query = _q(f"UPDATE meetings SET {assignments} WHERE id = ?")
    with _connect(db_path) as conn:
        with conn:
            conn.execute(
                query,
                (*updates.values(), meeting_id),
            )
    return get_meeting(db_path, meeting_id)

def delete_meeting(db_path, meeting_id: int) -> bool:
    query = _q("DELETE FROM meetings WHERE id = ?")
    with _connect(db_path) as conn:
        with conn:
            cursor = conn.execute(query, (meeting_id,))
            return cursor.rowcount > 0
